"use client";

import { cn } from "@/lib/utils";
import { motion, stagger, useAnimate, useInView } from "motion/react";
import { useEffect } from "react";

export const TypewriterEffect = ({
  words,
  className,
  cursorClassName,
  delay,
  staggerDuration,
}: {
  words: {
    text: string | React.ReactNode;
    className?: string;
  }[];
  className?: string;
  cursorClassName?: string;
  delay?: number;
  staggerDuration?: number;
}) => {
  // split text inside of words into array of characters
  const wordsArray = words.map((word) => {
    return {
      ...word,
      text: typeof word.text === "string" ? word.text.split("") : [word.text],
    };
  });

  const [scope, animate] = useAnimate();
  const isInView = useInView(scope);
  useEffect(() => {
    if (isInView) {
      const timeout = setTimeout(() => {
        animate(
          ".typer-char",
          {
            display: "inline-block",
            opacity: 1,
            width: "fit-content",
          },
          {
            duration: 0.1,
            delay: stagger(staggerDuration || 0.04),
            ease: "easeInOut",
          }
        );
      }, (delay || 0) * 1000);
      return () => clearTimeout(timeout);
    }
  }, [isInView, animate, delay, staggerDuration]);

  const renderWords = () => {
    return (
      <motion.div ref={scope} className="inline">
        {wordsArray.map((word, idx) => {
          return (
            <div key={`word-${idx}`} className="inline-block">
              {word.text.map((char, index) => (
                <motion.span
                  initial={{}}
                  key={`char-${index}`}
                  className={cn(
                    `dark:text-white text-black opacity-0 hidden typer-char`,
                    word.className
                  )}
                >
                  {char}
                </motion.span>
              ))}
              &nbsp;
            </div>
          );
        })}
      </motion.div>
    );
  };
  return (
    <div
      className={cn(
        "text-base font-medium flex flex-wrap items-center",
        className
      )}
    >
      {renderWords()}
      <motion.span
        initial={{
          opacity: 0,
        }}
        animate={{
          opacity: 1,
        }}
        transition={{
          duration: 0.8,
          repeat: Infinity,
          repeatType: "reverse",
        }}
        className={cn(
          "inline-block rounded-sm w-[2px] h-4 bg-primary",
          cursorClassName
        )}
      ></motion.span>
    </div>
  );
};

